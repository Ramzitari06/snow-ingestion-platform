CREATE DATABASE IF NOT EXISTS INGESTION_DB;

USE DATABASE INGESTION_DB;

CREATE SCHEMA IF NOT EXISTS RAW;

CREATE OR REPLACE TABLE RAW.CUSTOMERS (
    CUSTOMER_ID NUMBER,
    FIRSTNAME STRING,
    LASTNAME STRING,
    CITY STRING,
    CREATED_AT TIMESTAMP
);

CREATE OR REPLACE TABLE RAW.VALIDATIONS (
    VALIDATION_ID NUMBER,
    CUSTOMER_ID NUMBER,
    STATION STRING,
    LINE STRING,
    VALIDATION_DATETIME TIMESTAMP
);

CREATE OR REPLACE TABLE RAW.LOAD_HISTORY (
    LOAD_ID STRING,
    FILE_NAME STRING,
    TABLE_NAME STRING,
    LOAD_DATE TIMESTAMP,
    ROWS_LOADED NUMBER,
    STATUS STRING
);
